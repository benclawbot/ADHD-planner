import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createSyncServer} from '../server/sync-server.mjs';
import {createSyncClient} from '../src/sync-client.js';
const storage = () => {const m=new Map();return {getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,String(v)),removeItem:k=>m.delete(k)};};
const clone = value => structuredClone(value);
test('two independent devices sync online and reconcile offline edits through the actual server', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(),'tempo-e2e-'));
  const server = await createSyncServer({dataDir:dir});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const baseUrl=`http://127.0.0.1:${server.address().port}`;
  let stateA, stateB;
  const a=createSyncClient({storage:storage(),baseUrl,onRemoteState:s=>stateA=s,autoRetry:false});
  const b=createSyncClient({storage:storage(),baseUrl,onRemoteState:s=>stateB=s,autoRetry:false});
  await a.register('test@example.test','correct horse battery staple');
  const initial={schema:1,tasks:[{id:'one',title:'First',status:'open',notes:''}],captures:[],focus:null,settings:{}};
  a.setLocalState(initial);await a.syncNow();
  await b.login('test@example.test','correct horse battery staple');await b.syncNow();
  assert.equal(stateB.tasks[0].title,'First');
  const offlineA=clone(stateA),offlineB=clone(stateB);
  offlineA.tasks[0].title='Changed on A';offlineB.tasks[0].notes='Changed on B';
  a.setLocalState(offlineA);b.setLocalState(offlineB);
  await a.syncNow();await b.syncNow();await a.syncNow();
  assert.equal(stateA.tasks[0].title,'Changed on A');assert.equal(stateA.tasks[0].notes,'Changed on B');
  assert.deepEqual(stateA,stateB);
  const aConflict=clone(stateA),bConflict=clone(stateB);
  aConflict.tasks[0].title='A title';bConflict.tasks[0].title='B title';
  a.setLocalState(aConflict);b.setLocalState(bConflict);
  await a.syncNow();await b.syncNow();
  const history=await b.getHistory();
  assert.ok(history.history.length>0, 'conflicting version retained');
  assert.equal(b.getStatus().pendingCount,0);
});
